import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from 'pg';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(packageRoot, '../..');
const source = process.env.DATABASE_URL;
if (!source) throw new Error('DATABASE_URL is required; only a newly created disposable database is mutated.');
const databaseName = `ssoo_onboarding_verify_${process.pid}_${Date.now().toString(36)}`;
const targetUrl = new URL(source); targetUrl.pathname = `/${databaseName}`;
const adminUrl = new URL(source); adminUrl.pathname = '/postgres';
const admin = new Client({ connectionString: adminUrl.toString() });
await admin.connect();
let target; let db;
const keepFixture = process.argv.includes('--browser-fixture');
let succeeded = false;
const completed = [];
const pass = (name) => { completed.push(name); console.log(`[onboarding] passed: ${name}`); };
try {
  console.log(`[onboarding] creating disposable database: ${databaseName}`);
  await admin.query(`CREATE DATABASE "${databaseName}"`);
  target = new Client({ connectionString: targetUrl.toString() }); await target.connect();
  const migrationRoot = path.join(packageRoot, 'prisma/launch-migrations');
  const migrations = fs.readdirSync(migrationRoot).filter((name) => fs.existsSync(path.join(migrationRoot, name, 'migration.sql'))).sort();
  const onboardingMigration = '20261001090000_common_onboarding';
  for (const migration of migrations.filter((name) => name < onboardingMigration)) await target.query(fs.readFileSync(path.join(migrationRoot, migration, 'migration.sql'), 'utf8'));
  const seedRoot = path.join(packageRoot, 'prisma/seeds');
  const seedFiles = [...fs.readFileSync(path.join(seedRoot, 'apply_all_seeds.sql'), 'utf8').matchAll(/^\\i\s+(\S+)\s*$/gm)].map((match) => match[1]);
  for (const file of seedFiles.filter((name) => name !== '40_platform_onboarding_bootstrap.sql')) await target.query(fs.readFileSync(path.join(seedRoot, file), 'utf8'));
  const before = await target.query('SELECT user_id::text, role_code, is_active FROM common.cm_user_m ORDER BY user_id');
  await target.query(fs.readFileSync(path.join(migrationRoot, onboardingMigration, 'migration.sql'), 'utf8'));
  const after = await target.query('SELECT user_id::text, role_code, is_active FROM common.cm_user_m ORDER BY user_id');
  assert.deepEqual(after.rows, before.rows);
  assert.equal(Number((await target.query('SELECT count(*) FROM common.cm_platform_enrollment_h')).rows[0].count), before.rows.length);
  assert.equal(Number((await target.query('SELECT count(*) FROM common.cm_service_grant_h')).rows[0].count), before.rows.length * 4);
  pass('populated migration preserves existing accounts and records all admission evidence');
  for (const migration of migrations.filter(name => name > onboardingMigration)) await target.query(fs.readFileSync(path.join(migrationRoot, migration, 'migration.sql'), 'utf8'));
  const triggerRoot = path.join(packageRoot, 'prisma/triggers');
  for (const match of fs.readFileSync(path.join(triggerRoot, 'apply_all_triggers.sql'), 'utf8').matchAll(/^\\i\s+(\S+)\s*$/gm)) await target.query(fs.readFileSync(path.join(triggerRoot, match[1]), 'utf8'));
  process.env.DATABASE_URL = targetUrl.toString();
  const { DatabaseService } = await import(path.join(repoRoot, 'apps/server/dist/database/database.service.js'));
  const { PlatformAdmissionService } = await import(path.join(repoRoot, 'apps/server/dist/modules/common/onboarding/platform-admission.service.js'));
  const { OnboardingService } = await import(path.join(repoRoot, 'apps/server/dist/modules/common/onboarding/onboarding.service.js'));
  const { UserService } = await import(path.join(repoRoot, 'apps/server/dist/modules/common/user/user.service.js'));
  db = new DatabaseService(); await db.onModuleInit();
  const admission = new PlatformAdmissionService(db);
  const onboarding = new OnboardingService(db, admission);
  const users = new UserService(db);
  const adminUser = await db.client.user.findUniqueOrThrow({ where: { email: 'admin@company.com' } });
  assert.equal(await admission.isPlatformAdmin(adminUser.id), true);
  const created = await users.create({ loginId: 'onboarding-test', password: 'TestOnly123!x', userName: '온보딩 검증', email: 'new-onboarding@example.test', roleCode: 'user', departmentCode: 'UNAPPROVED-ORG' }, adminUser.id);
  const applicant = BigInt(created.id);
  assert.equal((await onboarding.snapshot(applicant)).status, 'pending');
  assert.equal(await db.client.userOrganizationRelation.count({ where: { userId: applicant } }), 0);
  await assert.rejects(() => admission.assertService(applicant, 'crm'));
  await users.update(applicant, { departmentCode: 'ANOTHER-UNAPPROVED' }, adminUser.id);
  assert.equal(await db.client.userOrganizationRelation.count({ where: { userId: applicant } }), 0);
  pass('admin-created account and profile edits cannot bypass onboarding');
  const organization = await db.client.organization.create({ data: { orgCode: 'ONBOARD-TEST-A', orgName: '검증 조직 A', orgType: 'internal' } });
  const anotherOrganization = await db.client.organization.create({ data: { orgCode: 'ONBOARD-TEST-B', orgName: '검증 조직 B', orgType: 'internal' } });
  const orgId = organization.orgId.toString();
  const membership = await onboarding.create(applicant, { kind: 'membership', organizationId: orgId, message: '소속 신청' });
  await assert.rejects(() => onboarding.create(applicant, { kind: 'membership', organizationId: orgId, message: '중복 신청' }));
  const service = await onboarding.create(applicant, { kind: 'service', organizationId: orgId, serviceCode: 'crm', message: 'CRM 신청' });
  const approve = { decision: 'approve', message: '검증 승인', roleCode: 'user' };
  await assert.rejects(() => onboarding.decide(BigInt(service.id), adminUser.id, approve));
  assert.equal(await db.client.serviceGrant.count({ where: { userId: applicant } }), 0);
  assert.equal((await db.client.onboardingRequest.findUniqueOrThrow({ where: { id: BigInt(service.id) } })).statusCode, 'pending');
  pass('duplicate requests and service approval before membership are rejected without partial writes');
  const decisions = await Promise.allSettled([onboarding.decide(BigInt(membership.id), adminUser.id, approve), onboarding.decide(BigInt(membership.id), adminUser.id, approve)]);
  assert.equal(decisions.filter((result) => result.status === 'fulfilled').length, 1);
  assert.equal(await db.client.userOrganizationRelation.count({ where: { userId: applicant, orgId: organization.orgId, isActive: true } }), 1);
  assert.equal((await onboarding.snapshot(applicant)).status, 'active');
  await assert.rejects(() => admission.assertService(applicant, 'crm'));
  await onboarding.decide(BigInt(service.id), adminUser.id, approve);
  await admission.assertService(applicant, 'crm');
  await assert.rejects(() => admission.assertService(applicant, 'dms'));
  assert.equal(await db.client.onboardingRequestHistory.count({ where: { id: BigInt(membership.id), eventType: 'U' } }), 1);
  pass('concurrent decisions commit exactly once; membership and app permissions remain separate');
  const authority = await onboarding.setAuthority(adminUser.id, { userId: applicant.toString(), authorityKind: 'service', organizationId: orgId, serviceCode: 'dms', maxRoleCode: 'user' });
  const ownRequest = await onboarding.create(applicant, { kind: 'service', organizationId: orgId, serviceCode: 'dms', message: '본인 신청' });
  await assert.rejects(() => onboarding.decide(BigInt(ownRequest.id), applicant, approve));
  assert.equal(await admission.isPlatformAdmin(applicant), false);
  const colleague = await users.create({ loginId: 'onboarding-colleague', password: 'TestOnly123!x', userName: '동료', email: 'colleague-onboarding@example.test', roleCode: 'user' }, adminUser.id);
  const colleagueId = BigInt(colleague.id);
  const colleagueMembership = await onboarding.create(colleagueId, { kind: 'membership', organizationId: orgId, message: '소속 신청' });
  await onboarding.decide(BigInt(colleagueMembership.id), adminUser.id, approve);
  const colleagueService = await onboarding.create(colleagueId, { kind: 'service', organizationId: orgId, serviceCode: 'dms', message: 'DMS 신청' });
  const otherService = await onboarding.create(colleagueId, { kind: 'service', organizationId: anotherOrganization.orgId.toString(), serviceCode: 'dms', message: '다른 조직' });
  assert.deepEqual((await onboarding.reviewQueue(applicant)).map((entry) => entry.id), [colleagueService.id]);
  await assert.rejects(() => onboarding.decide(BigInt(colleagueService.id), applicant, { ...approve, roleCode: 'manager' }));
  await assert.rejects(() => onboarding.decide(BigInt(otherService.id), applicant, approve));
  await onboarding.revokeAuthority(BigInt(authority.id), adminUser.id);
  await assert.rejects(() => onboarding.decide(BigInt(colleagueService.id), applicant, approve));
  pass('delegation excludes self, other organizations, higher roles, and revoked authorities');
  await db.client.userOrganizationRelation.updateMany({ where: { userId: applicant, orgId: organization.orgId }, data: { isActive: false } });
  await assert.rejects(() => admission.assertService(applicant, 'crm'));
  pass('membership revocation invalidates organization-scoped app grants immediately');
  const newOrg = await onboarding.create(colleagueId, { kind: 'organization', organizationName: '신규 검증 조직', message: '조직 생성 신청' });
  assert.equal(await db.client.organization.count({ where: { orgName: '신규 검증 조직' } }), 0);
  const approvedOrganization = await onboarding.decide(BigInt(newOrg.id), adminUser.id, approve);
  assert.ok(approvedOrganization.organizationId);
  assert.equal(await db.client.userOrganizationRelation.count({ where: { userId: colleagueId, orgId: BigInt(approvedOrganization.organizationId), isActive: true } }), 1);
  pass('new organization creation and applicant membership are atomic and approval-only');
  const manuallyLinked = await users.create({ loginId: 'onboarding-manual', password: 'TestOnly123!x', userName: '기존 조직 관리 연결', email: 'manual-onboarding@example.test', roleCode: 'user' }, adminUser.id);
  const manualId = BigInt(manuallyLinked.id);
  await db.client.userOrganizationRelation.create({ data: { userId: manualId, orgId: organization.orgId } });
  const manualService = await onboarding.create(manualId, { kind: 'service', organizationId: orgId, serviceCode: 'pms', message: '수동 연결 후 서비스 신청' });
  await assert.rejects(() => onboarding.decide(BigInt(manualService.id), adminUser.id, approve));
  assert.equal(await db.client.serviceGrant.count({ where: { userId: manualId } }), 0);
  const manualMembership = await onboarding.create(manualId, { kind: 'membership', organizationId: orgId, message: '기존 소속의 플랫폼 참여 승인' });
  await onboarding.decide(BigInt(manualMembership.id), adminUser.id, approve);
  await onboarding.decide(BigInt(manualService.id), adminUser.id, approve);
  assert.equal(await db.client.userOrganizationRelation.count({ where: { userId: manualId, orgId: organization.orgId, isActive: true } }), 1);
  await admission.assertService(manualId, 'pms');
  pass('manual organization assignment neither bypasses enrollment nor prevents the shared approval workflow');

  const cancelled = await onboarding.create(colleagueId, { kind: 'service', organizationId: orgId, serviceCode: 'sns', message: '취소 검증' });
  await onboarding.cancel(BigInt(cancelled.id), colleagueId);
  await assert.rejects(() => onboarding.decide(BigInt(cancelled.id), adminUser.id, approve));
  await target.query(fs.readFileSync(path.join(seedRoot, '40_platform_onboarding_bootstrap.sql'), 'utf8'));
  assert.equal((await onboarding.snapshot(applicant)).availableServices.includes('dms'), false);
  pass('cancelled requests cannot be approved; repeated bootstrap never admits new accounts');
  const { AccessFoundationService } = await import(path.join(repoRoot, 'apps/server/dist/modules/common/access/access-foundation.service.js'));
  const { AccessService: SnsAccessService } = await import(path.join(repoRoot, 'apps/server/dist/modules/sns/access/access.service.js'));
  const { SnsAiIndexAdapter } = await import(path.join(repoRoot, 'apps/server/dist/modules/sns/search/sns-ai-index.adapter.js'));
  const { AiIndexRegistryService } = await import(path.join(repoRoot, 'apps/server/dist/modules/common/ai-index/ai-index-registry.service.js'));
  const foundation = new AccessFoundationService(db, admission);
  const snsAccess = new SnsAccessService(db, foundation);
  const reader = await users.create({ loginId: 'onboarding-reader', password: 'TestOnly123!x', userName: '다른 조직 조회자', email: 'reader-onboarding@example.test', roleCode: 'manager' }, adminUser.id);
  const readerId = BigInt(reader.id);
  const readerToken = { userId: readerId.toString(), loginId: 'onboarding-reader' };
  assert.equal((await foundation.resolveActionPermissionContext(readerToken)).grantedPermissionCodes.size, 0);
  const readerMembership = await onboarding.create(readerId, { kind: 'membership', organizationId: anotherOrganization.orgId.toString(), message: '다른 조직 가입' });
  await onboarding.decide(BigInt(readerMembership.id), adminUser.id, approve);
  const readerService = await onboarding.create(readerId, { kind: 'service', organizationId: anotherOrganization.orgId.toString(), serviceCode: 'sns', message: 'SNS 조회' });
  await onboarding.decide(BigInt(readerService.id), adminUser.id, { ...approve, roleCode: 'viewer' });
  const permissions = (await foundation.resolveActionPermissionContext(readerToken)).grantedPermissionCodes;
  assert.equal(permissions.has('sns.feed.read'), true);
  assert.equal(permissions.has('sns.post.write'), false);
  assert.equal([...permissions].some((code) => code.startsWith('crm.')), false);
  const pmsRequest = await onboarding.create(readerId, { kind: 'service', organizationId: anotherOrganization.orgId.toString(), serviceCode: 'pms', message: 'PMS 조회' });
  await onboarding.decide(BigInt(pmsRequest.id), adminUser.id, { ...approve, roleCode: 'viewer' });
  assert.deepEqual(await foundation.getServiceRoleCodes(readerId, 'pms'), ['viewer']);
  const objectPermissions = await foundation.resolveObjectPermissionContext({ user: readerToken, targetObjectType: 'pms.project', targetObjectId: '123', domainGrantedPermissionCodes: ['pms.project.manage'] });
  assert.equal(objectPermissions.grantedPermissionCodes.has('pms.project.manage'), false);
  pass('new app roles override account defaults; viewer ownership cannot escalate mutation permissions');
  await assert.rejects(() => admission.resolveBusinessOrganization(readerId, 'pms'));
  const readerSecondMembership = await onboarding.create(readerId, { kind: 'membership', organizationId: orgId, message: '업무 조직 A 소속' });
  await onboarding.decide(BigInt(readerSecondMembership.id), adminUser.id, approve);
  const readerSecondService = await onboarding.create(readerId, { kind: 'service', organizationId: orgId, serviceCode: 'pms', message: '조직 A PMS 관리' });
  await onboarding.decide(BigInt(readerSecondService.id), adminUser.id, { ...approve, roleCode: 'manager' });
  assert.deepEqual((await admission.businessOrganizations(readerId, 'pms')).map((org) => org.orgId).sort(), [organization.orgId, anotherOrganization.orgId].sort());
  await assert.rejects(() => admission.resolveBusinessOrganization(readerId, 'pms'));
  await assert.rejects(() => admission.resolveBusinessOrganization(readerId, 'pms', anotherOrganization.orgId.toString()));
  await assert.rejects(() => admission.resolveBusinessOrganization(readerId, 'pms', approvedOrganization.organizationId));
  const { ProjectService } = await import(path.join(repoRoot, 'apps/server/dist/modules/pms/project/project.service.js'));
  const { ProjectOrgService } = await import(path.join(repoRoot, 'apps/server/dist/modules/pms/project/project-org.service.js'));
  const { ProjectRelationService } = await import(path.join(repoRoot, 'apps/server/dist/modules/pms/project/project-relation.service.js'));
  const { ProjectAccessService } = await import(path.join(repoRoot, 'apps/server/dist/modules/pms/project/project-access.service.js'));
  const projects = new ProjectService(db, foundation, new ProjectOrgService(db), new ProjectRelationService(db), { queueJob: async () => undefined }, admission);
  const projectAccess = new ProjectAccessService(db, foundation);
  const project = await projects.create({ projectName: '승인 조직 프로젝트', ownerOrganizationId: orgId, ownerId: readerId.toString() }, readerId);
  assert.equal(project.ownerOrganizationId, organization.orgId);
  await projects.update(project.id, { ownerId: colleagueId.toString() }, readerId);
  assert.equal((await db.client.project.findUniqueOrThrow({ where: { id: project.id } })).ownerOrganizationId, organization.orgId);
  await assert.rejects(() => projects.update(project.id, { ownerOrganizationId: null }, readerId));
  const readOnlyProject = await projects.create({ projectName: '조직 B 조회 프로젝트', ownerOrganizationId: anotherOrganization.orgId.toString(), ownerId: readerId.toString() }, adminUser.id);
  assert.equal((await projectAccess.getProjectAccess(readOnlyProject.id, readerToken)).features.canEditProject, false);
  const inaccessibleProject = await projects.create({ projectName: '다른 승인 조직 프로젝트', ownerOrganizationId: approvedOrganization.organizationId, ownerId: readerId.toString() }, adminUser.id);
  assert.equal((await projectAccess.getProjectAccess(inaccessibleProject.id, readerToken)).features.canViewProject, false);
  assert.equal((await projects.findAll({ page: 1, limit: 100 }, readerToken)).data.some((entry) => entry.id === inaccessibleProject.id), false);
  pass('PMS writes require an approved business organization; owner changes preserve it, roles and list/detail reads stay within the approved organization');

  const { verifyCrmOrganization } = await import('./verify-crm-organization.mjs');
  await verifyCrmOrganization({ db, admission, onboarding, foundation, readerId, readerToken, adminUser, organization, anotherOrganization, pass });

  const posts = [];
  for (const scope of ['public', 'organization', 'self']) posts.push(await db.client.snsPost.create({ data: {
    authorUserId: colleagueId, content: `온보딩 공개 범위 검증 ${scope}`, visibilityScopeCode: scope, targetOrgId: scope === 'organization' ? BigInt(approvedOrganization.organizationId) : null,
  } }));
  const adapter = new SnsAiIndexAdapter(db, new AiIndexRegistryService(), {}, snsAccess);
  for (const post of posts) {
    const canRead = await adapter.canRead({ sourceApp: 'sns', entityType: 'post', entityId: post.id.toString() }, readerToken);
    assert.equal(canRead, post.visibilityScopeCode === 'public');
  }
  const readerGrant = (await admission.grants(readerId)).find((grant) => grant.serviceCode === 'sns');
  await onboarding.revokeGrant(readerGrant.id, adminUser.id);
  assert.equal(await adapter.canRead({ sourceApp: 'sns', entityType: 'post', entityId: posts[0].id.toString() }, readerToken), false);
  pass('closed-platform public content crosses organizations; organization/private content and revoked service stay blocked in AI rechecks');
  const { verifySharing } = await import('./verify-sharing.mjs');
  const sharing = await verifySharing({ db, admission, onboarding, foundation, users, adminUser, organization, anotherOrganization, repoRoot, pass });
  if (keepFixture) {
    await users.create({ loginId: 'onboarding-browser', password: 'TestOnly123!x', userName: '온보딩 브라우저', email: 'browser-onboarding@example.test', roleCode: 'user' }, adminUser.id);
    fs.writeFileSync('/tmp/ssoo-onboarding-fixture.json', JSON.stringify({ databaseName, databaseUrl: targetUrl.toString(), sharing }), { mode: 0o600 });
  }
  succeeded = true;
  console.log(JSON.stringify({ success: true, checks: completed, database: databaseName }, null, 2));
} finally {
  if (db) await db.onModuleDestroy();
  if (target) await target.end();
  if (!keepFixture || !succeeded) {
  await admin.query('SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname=$1', [databaseName]);
  await admin.query(`DROP DATABASE IF EXISTS "${databaseName}"`);
  }
  await admin.end();
  console.log(`[onboarding] disposable database ${keepFixture && succeeded ? 'retained for browser verification' : 'removed'}: ${databaseName}`);
}
